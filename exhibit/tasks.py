def topo_sort(graph):
    nodes = set(graph)
    for deps in graph.values():
        nodes |= set(deps)
    deps_of = {n: set(graph.get(n, [])) for n in nodes}
    out, ready = [], sorted(n for n in nodes if not deps_of[n])
    seen = set()
    while ready:
        n = ready.pop(0)
        if n in seen:
            continue
        seen.add(n)
        out.append(n)
        newly = []
        for m in nodes - seen:
            if deps_of[m] and deps_of[m] <= seen:
                newly.append(m)
        for m in newly:
            if m not in ready:
                ready.append(m)
        ready = sorted(ready)
    if len(out) != len(nodes):
        raise ValueError("cycle detected")
    return out
