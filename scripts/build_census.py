#!/usr/bin/env python3
"""Generates census/index.md from the committed corpus.

The census page is the corpus made readable. It is GENERATED rather than
written, for the same reason published_figures.json is derived rather than
typed: a page stating "0 of 24" that someone edited by hand is a number with
nothing behind it, and this project has no standing to publish one.

    python scripts/build_census.py            # write census/index.md
    python scripts/build_census.py --check    # fail if the committed page is stale

`--check` runs in CI. A page that has drifted from the corpus it describes
fails the build rather than sitting there looking authoritative.

Only `framework_default` records exist in this repository, and the page says so
in its own text: a reader who finds 27 configurations here should know that is
the whole of what is published, not a sample of something larger.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))

from conformance.criteria import CRITERIA, applies  # noqa: E402
from conformance.report import derive_figures, load_corpus  # noqa: E402

OUT = pathlib.Path(__file__).resolve().parents[1] / "census" / "index.md"

SHORT = {c.id: c.id.split("_", 1)[0] for c in CRITERIA}
MARK = {"pass": "pass", "fail": "fail", "not_applicable": "n/a",
        "insufficient_evidence": "insufficient"}


def render(records: list[dict], fig: dict) -> str:
    out = []
    w = out.append
    w("---")
    w("layout: main")
    w("width: wide")
    w('title: "Configuration census: Evaluator Integrity"')
    w("---")
    w("")
    w("<!--")
    w("  GENERATED by scripts/build_census.py from conformance/corpus/.")
    w("  Do not edit this file. Edit the corpus and regenerate; a test asserts")
    w("  the two agree, so a hand edit here fails the build.")
    w("-->")
    w("")
    w("# Configuration census")
    w("")
    w(f"{fig['records_total']} evaluator configurations, scored against "
      f"[criteria v0.1](../criteria/v0.1/).")
    w("")
    w("Every configuration here is a **framework default**. That is what an")
    w("evaluation framework ships with out of the box, which anyone can install")
    w("and read. This is the whole of what we publish, not a sample of something")
    w("larger. Scores for organisations' own configurations are held elsewhere.")
    w("They are published only as totals, with no names attached.")
    w("")
    w("A verdict is not an opinion about a framework. The same framework can be")
    w("configured to pass or fail every criterion here. What is scored is one")
    w("configuration. Where a criterion belongs to the surrounding harness")
    w("rather than to the component being scored, it reads `n/a` rather than")
    w("`fail`.")
    w("")
    w("## What the corpus shows")
    w("")
    w(f"- **{fig['c1_pass']} of {fig['records_in_c1_scope']}** configurations in")
    w("  scope satisfy C1. None of them commits to an answer of its own before")
    w("  seeing the candidate.")
    w(f"- **{fig['recompute_variants']} of {fig['records_in_c1_scope']}** are")
    w("  recompute variants. They tell the judge to solve the problem first,")
    w("  in a prompt that already contains the candidate. The cited source")
    w("  measures that as a failure, not a partial fix.")
    w(f"- **{fig['reference_supplied']} of {fig['reference_supplied_of']}** are")
    w("  handed a reference answer. A reference given to the judge is not")
    w("  independent of the judge, so it does not satisfy C2.")
    w(f"- **{fig['packages_count']} packages** from")
    w(f"  **{fig['vendors_count']} vendors**.")
    w("")
    w("## The configurations")
    w("")
    w("| configuration | task class | " +
      " | ".join(SHORT[c.id] for c in CRITERIA) + " | evidence |")
    w("|---|---|" + "---|" * len(CRITERIA) + "---|")
    for r in sorted(records, key=lambda x: x["config_id"]):
        cells = []
        for c in CRITERIA:
            a = (r.get("assessments") or {}).get(c.id)
            cells.append(MARK.get((a or {}).get("verdict"), "—"))
        w(f"| `{r['config_id']}` | {r['task_class']} | " + " | ".join(cells) +
          f" | [source]({r['source_url']}) |")
    w("")
    w("## Reading a verdict")
    w("")
    w("Each verdict rests on a quote from the exact file the record names. The")
    w("file is pinned by digest, not by version string, so anyone can obtain")
    w("the same bytes. The records are JSON, one per configuration,")
    w("in [`conformance/corpus/`](https://github.com/idilgozel/evaluator-integrity/tree/main/conformance/corpus).")
    w("")
    w("`insufficient` is not a soft `fail`. It means the evidence needed to")
    w("score the criterion was not shown. That is the honest verdict when")
    w("nobody has measured the thing.")
    w("")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true",
                   help="fail if the committed page is not what this would "
                        "generate; does not write")
    args = p.parse_args(argv)

    records = load_corpus()
    text = render(records, derive_figures(records))

    if args.check:
        if not OUT.exists():
            print(f"{OUT} does not exist; run without --check.", file=sys.stderr)
            return 1
        if OUT.read_text() != text:
            print(f"{OUT} is stale: it no longer matches the corpus it "
                  f"describes.\nRegenerate with: python scripts/build_census.py",
                  file=sys.stderr)
            return 1
        print("census page matches the corpus.")
        return 0

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(records)} records)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
